#!/bin/sh
# ==============================================================================
# Horus-Spot — Walled Garden (IPs and Domains)
# ------------------------------------------------------------------------------
# Applies Walled Garden IPs and Domains.
# ==============================================================================

. /lib/functions.sh

DNSMASQ_CONF="/tmp/dnsmasq.d/uspot-walledgarden.conf"
mkdir -p /tmp/dnsmasq.d

# Ensure nftables set exists and rule exists
nft list set inet uspot walled_garden_ips >/dev/null 2>&1 || nft add set inet uspot walled_garden_ips '{ type ipv4_addr; flags interval; }'
nft list chain inet uspot prerouting | grep -q "walled_garden_ips" || nft insert rule inet uspot prerouting ip daddr @walled_garden_ips accept

# Flush the set (dnsmasq will repopulate domains when restarted, we will repopulate IPs now)
nft flush set inet uspot walled_garden_ips

# Prepare fresh dnsmasq conf
echo "# Auto-generated by uspot-walledgarden.sh" > "$DNSMASQ_CONF"
RESTART_DNSMASQ=0

apply_ip() {
	local cfg="$1"
	local ip enabled
	config_get ip "$cfg" ip ""
	config_get_bool enabled "$cfg" enabled 1
	[ -z "$ip" ] && return 0
	
	if [ "$enabled" = "1" ]; then
		nft add element inet uspot walled_garden_ips "{ $ip }"
		logger -t horus-spot "Walled-Garden: allowed IP $ip"
	fi
}

apply_domain() {
	local cfg="$1"
	local domain enabled
	config_get domain "$cfg" domain ""
	config_get_bool enabled "$cfg" enabled 1
	[ -z "$domain" ] && return 0
	
	if [ "$enabled" = "1" ]; then
		# tell dnsmasq to resolve this domain and put IPs into our nftables set!
		echo "nftset=/${domain}/inet#uspot#walled_garden_ips" >> "$DNSMASQ_CONF"
		RESTART_DNSMASQ=1
		logger -t horus-spot "Walled-Garden: allowed Domain $domain"
	fi
}

case "$1" in
	apply|"")
		config_load uspot
		config_foreach apply_ip walled_ip
		config_foreach apply_domain walled_domain
		
		# Restart dnsmasq only if we have domains
		if [ "$RESTART_DNSMASQ" = "1" ] || [ -f "$DNSMASQ_CONF" ]; then
			/etc/init.d/dnsmasq restart
		fi
		;;
	*)
		echo "Usage: $0 apply"
		exit 1
		;;
esac

exit 0
